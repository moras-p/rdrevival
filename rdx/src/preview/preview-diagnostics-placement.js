import { PreviewActorSystem } from './preview-actors.js';
import { projectRdxDescriptor, projectRuntimeCollisionPatch, collisionSemanticName } from '../collision/descriptor-semantics.js';
import { rotateSpriteFrame } from './preview-render-primitives.js';
import { classicPreviewKind, firstVisibleSample } from './preview-production-state.js';
import { sceneryAssemblyFrame, reviewedRdxTraps, reviewedAbsentClassicHazards, descriptorStaticSceneryVisuals, classicTerrainHazardRects } from './preview-static-renderer.js';

export function systemModificationDiagnostics() {
  if (!this.selection || this.selection.visualSource === 'classic') return Object.freeze([]);
  const submap = Number(this.selection.submap), mapId = Number(this.selection.mapId);
  const stateNote = () => this.systemModificationsEnabled ? 'currently applied' : 'currently withheld from raw RDX baseline';
  const trapOwnedCells = new Set(reviewedRdxTraps(this.trapRegistry, submap, mapId).flatMap(trap => {
    const state = String(trap?.state || 'static');
    const bounds = Array.isArray(trap?.contact?.bounds) ? trap.contact.bounds.map(Number) : [];
    if (state === 'inactive' || bounds.length !== 4 || bounds[2] <= 0 || bounds[3] <= 0) return [];
    const out = [];
    for (let y = bounds[1]; y < bounds[1] + bounds[3]; y += 8) for (let x = bounds[0]; x < bounds[0] + bounds[2]; x += 8)
      out.push(`${Math.floor(x / 8)}:${Math.floor(y / 8)}`);
    return out;
  }));
  const roomAudit = (this.placementAudit?.rooms || []).find(row => Number(row.submap) === submap && Number(row.mapId) === mapId);
  const auditById = new Map((roomAudit?.items || []).flatMap(item => [
    [String(item.id || ''), item], [String(item.sourceKey || ''), item]
  ]));
  const box = raw => Array.isArray(raw) && raw.length >= 4 ? Object.freeze({
    x:Number(raw[0]), y:Number(raw[1]), width:Math.max(1,Number(raw[2])), height:Math.max(1,Number(raw[3]))
  }) : null;
  const rows = [];

  /* Exact placement deltas are generated by the reviewed placement-correction
   * system and applied by PreviewActorSystem. Keep raw and fitted boxes side
   * by side so Diagnostics can explain the transformation even while it is
   * deliberately withheld in raw-RDX mode. */
  for (const correction of this.actorSystem?.visualPlacementCorrections?.rows || []) {
    if (Number(correction.submap) !== submap || Number(correction.mapId) !== mapId) continue;
    const sourceKey = `mark:${Number(correction.mark)}`;
    const audit = auditById.get(String(correction.sourceId || '')) || auditById.get(sourceKey) || null;
    const currentOrigin = Array.isArray(correction.currentOrigin) ? correction.currentOrigin.map(Number) : [0,0];
    const fittedOrigin = Array.isArray(correction.fittedOrigin) ? correction.fittedOrigin.map(Number) : [currentOrigin[0] + Number(correction.dx || 0), currentOrigin[1] + Number(correction.dy || 0)];
    const currentBounds = box(audit?.currentBounds) || Object.freeze({x:currentOrigin[0]-8,y:currentOrigin[1]-16,width:16,height:16});
    const fittedBounds = box(audit?.fittedBounds) || Object.freeze({x:fittedOrigin[0]-8,y:fittedOrigin[1]-16,width:16,height:16});
    rows.push(Object.freeze({
      debugId:`system-placement:${sourceKey}`, sourceKey, category:'placement', subjectCategory:String(correction.subjectCategory || audit?.subjectCategory || 'actor'),
      overlayType:'system-placement-correction', classification:'applied-system-modification', current:Object.freeze(currentOrigin), bounds:fittedBounds,
      currentBounds, fittedBounds, currentOrigin:Object.freeze(currentOrigin), fittedOrigin:Object.freeze(fittedOrigin),
      drift:Object.freeze([Number(correction.dx || 0), Number(correction.dy || 0)]), preferFitted:true,
      authority:'visual-placement-correction', reason:String(correction.provenance || ''), applied:this.systemModificationsEnabled,
      policy:Object.freeze({family:'placement',label:`placement correction · ${Number(correction.dx || 0)},${Number(correction.dy || 0)}`}),
      notes:Object.freeze([String(correction.provenance || ''), stateNote()].filter(Boolean))
    }));
  }

  /* These are the reviewed visual actions that staticLayers()/dynamicFrame()
   * actually apply. Geometry-only rows from the same source file are omitted
   * here; their effective raw→production delta is reported below instead. */
  const staticVisualActions = new Set(['suppress','overlay-tiles','overlay-color','relocate','copy']);
  for (const patch of this.reviewedMapVisualPatches) {
    if (Number(patch.submap) !== submap || Number(patch.mapId) !== mapId || !staticVisualActions.has(String(patch.action))) continue;
    const bounds = box(patch.bounds); if (!bounds) continue;
    rows.push(Object.freeze({
      debugId:`system-visual:${String(patch.id)}`, sourceKey:String(patch.sourceKey || `map-visual:${patch.id}`),
      traceCollection:'reviewedMapVisualPatches', category:'patch', subjectCategory:'presentation', overlayType:'system-visual-patch',
      classification:'applied-system-modification', current:Object.freeze([bounds.x+bounds.width/2,bounds.y+bounds.height/2]), bounds,
      envelope:Object.freeze({minX:bounds.x,minY:bounds.y,maxX:bounds.x+bounds.width,maxY:bounds.y+bounds.height,width:bounds.width,height:bounds.height,sampleCount:1}),
      applied:this.systemModificationsEnabled, authority:String(patch.authority || 'reviewed-map-visual-patch'),
      policy:Object.freeze({family:'patch',label:`reviewed ${patch.layer || 'map'} visual ${patch.action}`}),
      notes:Object.freeze([String(patch.reason || ''), String(patch.provenance || ''), stateNote()].filter(Boolean))
    }));
  }

  const palette = this.paletteRegistry.forMap(mapId).rgba;
  for (const patch of this.reviewedMapVisualPatches) {
    if (Number(patch.submap) !== submap || Number(patch.mapId) !== mapId || !['actor-pn','overlay-pn'].includes(String(patch.action))) continue;
    const origin = Array.isArray(patch.origin) ? patch.origin.map(Number) : null, pn = Number(patch.pn);
    if (!origin || origin.length < 2 || !Number.isFinite(pn)) continue;
    const quarterTurns = Number(patch.quarterTurns || 0) & 3;
    let frame = rotateSpriteFrame(this._frameForPn(pn, 0, palette, {mirrorX:!!patch.mirrorX,mirrorY:!!patch.mirrorY,rawRdxPn:patch.action==='actor-pn'}), quarterTurns);
    let drawX=origin[0]-8, drawY=origin[1]-16, width=16, height=16;
    if (frame) {
      let anchor={x:Number(frame.originX || 0),y:Number(frame.originY || 0)};
      if (patch.action === 'actor-pn') anchor=this.spriteDecoder.placementAnchor(frame, Number(patch.actorId || 0), {role:patch.role || 'actor'});
      drawX=Math.round(origin[0]-Number(anchor.x || 0)); drawY=Math.round(origin[1]-Number(anchor.y || 0)); width=frame.pixels.width; height=frame.pixels.height;
    }
    const bounds=Object.freeze({x:drawX,y:drawY,width,height});
    rows.push(Object.freeze({
      debugId:`system-visual:${String(patch.id)}`, sourceKey:String(patch.sourceKey || `map-visual:${patch.id}`),
      traceCollection:'reviewedMapVisualPatches', category:'patch', subjectCategory:String(patch.role || 'actor'), overlayType:'system-pn-override',
      classification:'applied-system-modification', current:Object.freeze(origin), bounds, applied:this.systemModificationsEnabled,
      authority:String(patch.authority || 'reviewed-pn-override'), policy:Object.freeze({family:'patch',label:`reviewed ${patch.action} · PN ${pn}`}),
      notes:Object.freeze([String(patch.reason || ''), String(patch.provenance || ''), stateNote()].filter(Boolean))
    }));
  }

  /* Descriptor scenery replacement is another production transformation: it
   * detaches embedded RDX map pixels and re-renders an authored reusable trap
   * asset. Report it as one coherent system change rather than exposing the
   * internal detach and redraw operations as unrelated patches. */
  for (const scenery of descriptorStaticSceneryVisuals(this.trapRegistry, submap, mapId)) {
    const frame=sceneryAssemblyFrame(this.spriteDecoder,palette,scenery.asset,this);
    const drawX=Number(scenery.position?.[0] || 0), drawY=Number(scenery.position?.[1] || 0);
    const bounds=Object.freeze({x:drawX,y:drawY,width:Math.max(1,Number(frame?.pixels?.width || 16)),height:Math.max(1,Number(frame?.pixels?.height || 16))});
    rows.push(Object.freeze({
      debugId:`system-descriptor-scenery:${String(scenery.trap?.id || scenery.trap?.sourceKey || `${drawX}:${drawY}`)}`,
      sourceKey:String(scenery.trap?.sourceKey || `trap:${scenery.trap?.id || 'descriptor-scenery'}`), category:'patch', subjectCategory:'scenery',
      overlayType:'system-descriptor-scenery', classification:'applied-system-modification', current:Object.freeze([drawX+bounds.width/2,drawY+bounds.height/2]), bounds,
      applied:this.systemModificationsEnabled, authority:'trap-descriptor-reusable-scenery', policy:Object.freeze({family:'patch',label:'descriptor scenery replacement'}),
      notes:Object.freeze([`asset family: ${String(scenery.trap?.family || 'unclassified')}`, stateNote()])
    }));
  }

  /* Report collision systems by effect, not by data-source membership. This
   * captures explicit runtime patches as well as inferred Classic/RDX
   * correspondence and square-hole clearance corrections. */
  const width8=Math.ceil(Number(this.selection.dimensions?.width || 0)/8), height8=Math.ceil(Number(this.selection.dimensions?.height || 0)/8);
  for (let gy=0; gy<height8; ++gy) for (let gx=0; gx<width8; ++gx) {
    const descriptor=this._rdxDescriptorAtGrid(gx,gy);
    if (descriptor.mt == null || descriptor.ml == null || descriptor.editorGeometry) continue;
    const raw=projectRdxDescriptor(descriptor.mt,descriptor.ml,descriptor.qy);
    const classicComparison=this._classicComparisonForRdxGrid(gx,gy), classicFlags=classicComparison.flags;
    const correspondence=this._classicMaskForRdxDescriptor(descriptor);
    const patch=this.runtimeCollisionPatchByCell.get(`${submap}:${mapId}:${gx}:${gy}`) || null;
    const corrected=patch ? projectRuntimeCollisionPatch(patch.action,classicFlags) : projectRdxDescriptor(descriptor.mt,descriptor.ml,descriptor.qy,classicFlags,{
      qx:descriptor.qx,
      squareHoleClearance:this._squareHoleClearanceAtGrid(gx,gy,descriptor,classicFlags,classicComparison.inBounds),
      correspondenceMask:correspondence.status==='confident'?correspondence.mask:null,
      matchedActivator:correspondence.activatorMatches?.length>0,
      requireFullLadderWidth:submap===9&&mapId===13
    });
    const rawFlags=Number(raw.flags || 0)&0xff, correctedFlags=Number(corrected.flags || 0)&0xff;
    if (rawFlags===correctedFlags) continue;
    /* Semantic terrain hazards already expose the reviewed hazard/contact box
     * in Scene + Diagnostics. When an explicit trap owns this corrected lethal
     * cell, keep the user-facing representation there instead of duplicating a
     * second generic system-collision patch row on top of the same 8x8 box. */
    if (patch && trapOwnedCells.has(`${gx}:${gy}`) && (correctedFlags & 0x04)) continue;
    const bounds=Object.freeze({x:gx*8,y:gy*8,width:8,height:8});
    const authority=patch?'reviewed-runtime-collision-patch':String(corrected.source || 'derived-collision-correction');
    rows.push(Object.freeze({
      debugId:`system-collision:${gx}:${gy}`, sourceKey:String(patch?.id || `geometry:rdx:g8:${gx}:${gy}`), category:'patch', subjectCategory:'collision',
      overlayType:'system-collision-delta', classification:'applied-system-modification', current:Object.freeze([bounds.x+4,bounds.y+4]), bounds,
      applied:this.systemModificationsEnabled, authority, policy:Object.freeze({family:'patch',label:`collision correction · ${collisionSemanticName(rawFlags)} → ${collisionSemanticName(correctedFlags)}`}),
      notes:Object.freeze([`raw 0x${rawFlags.toString(16).padStart(2,'0')} → production 0x${correctedFlags.toString(16).padStart(2,'0')} (${corrected.source})`, patch?`runtime patch: ${String(patch.action || patch.id || 'reviewed')}`:'derived from RDX/Classic correspondence', stateNote()])
    }));
  }
  return Object.freeze(rows);
}

export function placementDiagnostics() {
  if (!this.selection) return Object.freeze([]);
  const room = (this.placementAudit?.rooms || []).find(row =>
    Number(row.submap) === Number(this.selection.submap) && Number(row.mapId) === Number(this.selection.mapId));
  if (!room || !Array.isArray(room.items)) return Object.freeze([]);
  const box = raw => raw && raw.length >= 4 ? Object.freeze({ x:Number(raw[0]), y:Number(raw[1]), width:Number(raw[2]), height:Number(raw[3]) }) : null;
  const classic = this.selection.visualSource === 'classic';
  return Object.freeze(room.items.map(item => {
    const rawClassicBounds = box(item.classicBounds);
    const classicBounds = classic && rawClassicBounds ? this._classicPreviewBounds(rawClassicBounds) : rawClassicBounds;
    const productionBounds = box(item.currentBounds), fittedRdxBounds = box(item.fittedBounds);
    /* Side-by-side Placement must show the exact matching Classic source
     * geometry in the Classic pane, not merely RDX current/fitted boxes. */
    const currentBounds = classic ? classicBounds : productionBounds;
    const fittedBounds = classic ? classicBounds : fittedRdxBounds;
    const bounds = fittedBounds || currentBounds;
    if (!bounds) return null;
    const current = classic
      ? [bounds.x + bounds.width / 2, bounds.y + bounds.height / 2]
      : (item.fittedOrigin || [bounds.x + bounds.width / 2, bounds.y + bounds.height / 2]);
    return Object.freeze({
      debugId: `placement:${String(item.id || item.sourceKey || 'item')}`,
      sourceKey: String(item.sourceKey || ''), category: 'placement', subjectCategory: String(item.subjectCategory || 'actor'),
      overlayType: 'placement', classification: String(item.status || 'review'), placementStatus: String(item.status || 'review'),
      current: Object.freeze([Number(current[0]), Number(current[1])]), bounds,
      currentBounds, fittedBounds, classicBounds, classicReference: classic,
      currentOrigin: classic ? current : item.currentOrigin, fittedOrigin: classic ? current : item.fittedOrigin,
      drift: Object.freeze(classic ? [0,0] : (item.drift || [0,0]).map(Number)), preferFitted: classic ? false : !!item.preferFitted,
      confidence: item.confidence || null, authority: classic ? 'classic-source-placement-reference' : (item.authority || 'entity-placement-audit'), reason: item.reason || '',
      envelope: Object.freeze({ minX:bounds.x, minY:bounds.y, maxX:bounds.x+bounds.width, maxY:bounds.y+bounds.height,
        width:bounds.width, height:bounds.height, sampleCount:1 }),
      policy: Object.freeze({ family:'placement', label:`${classic ? 'Classic source · ' : ''}${item.subjectCategory || 'entity'} placement · ${item.status || 'review'}` }),
      notes: Object.freeze([String(item.reason || ''), classic ? 'Exact Classic source/reference geometry.' : `drift ${Number(item.drift?.[0] || 0)},${Number(item.drift?.[1] || 0)}`])
    });
  }).filter(Boolean));
}

export function noOverlapDiagnostics(tick = 0, selectables = []) {
  if (!this.selection) return Object.freeze([]);
  const precomputedRoom = (this.noOverlapPresence?.rooms || []).find(row =>
    Number(row.submap) === Number(this.selection.submap) && Number(row.mapId) === Number(this.selection.mapId));

  /* Side-by-side No-overlap is a correspondence audit, so the Classic pane
   * must draw the source geometry that produced each RDX-side diagnostic.
   * Earlier builds returned no rows at all for Classic, which made real
   * Classic lethal tiles look "missing" simply because only the RDX pane
   * had a debug rectangle.  Terrain ids are reconstructed from xrick's
   * MAP_EFLG_LETHAL groups; marked entities use the exact captured Classic
   * source rectangle. */
  if (this.selection.visualSource === 'classic') {
    if (!precomputedRoom || !Array.isArray(precomputedRoom.missing)) return Object.freeze([]);
    const classicRoom = this._classicPreviewRoom(this.selection.submap);
    const hazards = classicTerrainHazardRects(classicRoom, this.trapRegistry);
    const productionRoom = this._productionRoom();
    const boxFromRow = row => {
      const sourceKey = String(row.sourceKey || '').replace(/^terrain-hazard:/, '');
      const hazardMatch = /^classic-sm[0-9a-f]+-(\d+)$/i.exec(sourceKey);
      if (hazardMatch) {
        const hazard = hazards[Number(hazardMatch[1])];
        if (hazard?.bounds) return { bounds: hazard.bounds, sourceKey: `terrain-hazard:${sourceKey}` };
      }
      const markMatch = /^mark:(\d+)$/i.exec(sourceKey);
      if (markMatch) {
        const mark = Number(markMatch[1]);
        const classic = (productionRoom?.classicActors || []).find(item => Number(item?.source?.mark ?? item?.mark) === mark) || null;
        const sample = classic ? firstVisibleSample(classic, 'draw') : null;
        const draw = sample?.draw || classic?.draw || null;
        const source = classic?.source || (classicRoom?.entities || []).find(item => Number(item.mark) === mark) || null;
        if (draw || source) {
          const x = Number(draw?.[0] ?? source?.x ?? 0);
          const y = draw ? Number(draw[1]) + this._classicPreviewYOffset() : Number(source?.y ?? 0);
          const width = Math.max(8, Number(source?.w || 16)), height = Math.max(8, Number(source?.h || 16));
          return { bounds: { x, y, width, height }, sourceKey: `mark:${mark}` };
        }
      }
      return null;
    };
    return Object.freeze(precomputedRoom.missing.map(row => {
      const source = boxFromRow(row);
      if (!source?.bounds) return null;
      const b = source.bounds;
      const current = Object.freeze([Number(b.x) + Number(b.width) / 2, Number(b.y) + Number(b.height) / 2]);
      return Object.freeze({
        ...row, debugId: `no-overlap-classic:${String(row.debugId || source.sourceKey)}`, sourceKey: source.sourceKey,
        category: 'no-overlap', overlayType: 'classic-no-overlap-source', current, bounds: Object.freeze({ ...b }),
        envelope: Object.freeze({ minX:b.x, minY:b.y, maxX:b.x+b.width, maxY:b.y+b.height, width:b.width, height:b.height, sampleCount:1 }),
        policy: Object.freeze({ family:'no-overlap', label:`Classic source · ${row.policy?.label || row.classification || 'presence diagnostic'}` }),
        authority: 'classic-source-geometry-for-no-overlap-correspondence',
        notes: Object.freeze([...(row.notes || []), 'Exact Classic source geometry shown for side-by-side correspondence.'])
      });
    }).filter(Boolean));
  }
  /* v2.1.53: this audit is static room evidence. Recomputing the complete
   * Classic↔RDX proximity search on every preview frame made No overlap an
   * accidental O(frame × entities × candidates) hot path and could lock the
   * browser. Prefer the release-generated room report; retain the local
   * calculation below only as a development fallback when that file is absent. */
  if (precomputedRoom && Array.isArray(precomputedRoom.missing))
    return Object.freeze(precomputedRoom.missing.map(row => Object.freeze({ ...row })));
  const level = this.selection.level || {};
  const pixelOffset = level.pixelOffset || {};
  const dx = Number(pixelOffset.dxPx || 0), dy = Number(pixelOffset.dyPx || 0);
  const room = this._classicRoom(this.selection.submap);
  const rdxItems = (selectables || []).filter(item => item?.port === 'rdx' && item.visible !== false);
  const center = item => {
    const b = item?.bounds;
    if (b) return [Number(b.x) + Number(b.width) / 2, Number(b.y) + Number(b.height) / 2];
    return [Number(item?.x || 0), Number(item?.y || 0)];
  };
  const distance = (a, b) => Math.hypot(Number(a[0]) - Number(b[0]), Number(a[1]) - Number(b[1]));
  const compatibleCategory = (classicKind, item) => {
    const category = String(item?.category || item?.kind || '');
    if (classicKind === 'explodable') return ['explodable','blockage'].includes(category);
    if (classicKind === 'blockage') return ['blockage','explodable'].includes(category);
    return category === classicKind || (classicKind === 'trap' && ['trap','projectile'].includes(category));
  };
  const output = [];
  for (const entity of room.entities || []) {
    const sourceKey = `mark:${Number(entity.mark)}`;
    if (rdxItems.some(item => String(item.sourceKey || '') === sourceKey)) continue;
    const classicKind = classicPreviewKind('', Number(entity.entity));
    /* Generic controller records are intentionally omitted: No overlap is a
     * presence-audit view for visible/interactive gameplay families, not a
     * dump of invisible Classic bookkeeping entities. */
    if (!['enemy','collectible','trap','blockage','explodable'].includes(classicKind)) continue;
    const expected = [Number(entity.x || 0) + dx, Number(entity.y || 0) + dy];
    const nearby = rdxItems.filter(item => compatibleCategory(classicKind, item))
      .some(item => distance(expected, center(item)) <= 56);
    if (nearby) continue;
    const w = Math.max(8, Number(entity.w || 16)), h = Math.max(8, Number(entity.h || 16));
    output.push(Object.freeze({
      debugId: `no-overlap:${sourceKey}`, sourceKey, category: 'no-overlap', subjectCategory: classicKind,
      classification: 'missing-rdx-entity', counterpartState: 'no-compatible-rdx-entity-nearby',
      overlayType: 'missing-rdx-entity', current: Object.freeze(expected),
      bounds: Object.freeze({ x: Math.round(expected[0] - w / 2), y: Math.round(expected[1] - h), width: w, height: h }),
      policy: Object.freeze({ family: 'no-overlap', label: `Classic ${classicKind} has no nearby RDX counterpart` }),
      authority: 'classic-to-rdx-general-area-presence-audit',
      notes: Object.freeze([`Classic mark ${entity.mark} / entity 0x${Number(entity.entity).toString(16).padStart(2,'0')} projected with room offset (${dx},${dy}); no compatible RDX ${classicKind} within 56px.`])
    }));
  }

  const classicHazards = classicTerrainHazardRects(room, this.trapRegistry);
  const reviewedTraps = reviewedRdxTraps(this.trapRegistry, this.selection.submap, this.selection.mapId);
  const reviewedAbsences = new Set(reviewedAbsentClassicHazards(this.trapRegistry, this.selection.submap, this.selection.mapId)
    .map(row => String(row.sourceKey || '')).filter(Boolean));
  const hazardCenter = bounds => [Number(bounds.x) + Number(bounds.width) / 2, Number(bounds.y) + Number(bounds.height) / 2];
  const hazardCapableItems = rdxItems.filter(item => {
    const category = String(item?.category || item?.kind || item?.role || '');
    return !!item?.hazardPotential || ['trap','projectile','shooter'].includes(category);
  });
  const possibleHazardVisualItems = rdxItems.filter(item => {
    const category = String(item?.category || item?.kind || item?.role || '');
    return ['trap','projectile','shooter','actor','blockage','explodable'].includes(category);
  });
  const nearestWithin = (items, point, radius) => {
    let winner = null;
    for (const item of items) {
      const candidateDistance = distance(point, center(item));
      if (candidateDistance > radius || (winner && candidateDistance >= winner.distance)) continue;
      winner = { item, distance: candidateDistance };
    }
    return winner;
  };
  classicHazards.forEach((hazard, index) => {
    const expectedBounds = Object.freeze({
      x: Number(hazard.bounds.x) + dx, y: Number(hazard.bounds.y) + dy,
      width: Number(hazard.bounds.width), height: Number(hazard.bounds.height)
    });
    const expectedCenter = hazardCenter(expectedBounds);
    const classicId = `classic-sm${String(this.selection.submap).padStart(2,'0')}-${index}`;
    const classicSourceKey = `terrain-hazard:${classicId}`;
    /* A reviewed absence is correspondence evidence too: the Classic lethal
     * strip was removed by the RDX room redesign. Do not draw the coarse
     * projection as a missing/candidate hazard in the RDX pane. */
    if (reviewedAbsences.has(classicSourceKey)) return;
    const exactReviewed = reviewedTraps.find(row => String(row?.classicParentSourceKey || '') === classicSourceKey) || null;
    const matchedReviewed = exactReviewed || reviewedTraps.find(row => {
      const b = row?.contact?.bounds;
      if (!Array.isArray(b) || b.length < 4) return false;
      const rb = { x:Number(b[0]), y:Number(b[1]), width:Number(b[2]), height:Number(b[3]) };
      return distance(expectedCenter, hazardCenter(rb)) <= 40;
    }) || null;
    if (matchedReviewed) return;

    /* Do not collapse an unreviewed nearby RDX trap into "matched".  It is
     * valuable asset-research evidence, but until source/type ownership is
     * reviewed it cannot prove Classic↔RDX hazard parity.  Surface it as a
     * distinct candidate so No overlap helps finish the mapping instead of
     * making the uncertainty disappear. */
    const hazardCandidate = nearestWithin(hazardCapableItems, expectedCenter, 64);
    if (hazardCandidate) {
      const candidate = hazardCandidate.item;
      output.push(Object.freeze({
        debugId: `no-overlap:${classicId}:candidate:${candidate.sourceKey || candidate.elementId || 'rdx-hazard'}`,
        sourceKey: classicSourceKey,
        rdxSourceKey: candidate.sourceKey || null,
        category: 'no-overlap', subjectCategory: 'hazard', classification: 'candidate-rdx-hazard-entity-unlinked',
        counterpartState: 'nearby-hazard-capable-rdx-entity-needs-source-link-review', overlayType: 'candidate-rdx-hazard',
        current: Object.freeze(expectedCenter), bounds: expectedBounds,
        policy: Object.freeze({ family: 'no-overlap', label: 'Nearby RDX hazard entity needs Classic source/type review' }),
        authority: 'classic-lethal-tile-to-rdx-hazard-candidate-audit',
        notes: Object.freeze([
          `Classic ${classicId} projects to [${expectedBounds.x},${expectedBounds.y},${expectedBounds.width},${expectedBounds.height}].`,
          `Nearest hazard-capable RDX entity is ${candidate.elementId || candidate.sourceKey || 'unknown'} at ${hazardCandidate.distance.toFixed(1)}px; keep visible in No overlap until its Classic parent/type is reviewed.`
        ])
      }));
      return;
    }

    const visualCandidate = nearestWithin(possibleHazardVisualItems, expectedCenter, 32);
    if (visualCandidate) {
      const candidate = visualCandidate.item;
      output.push(Object.freeze({
        debugId: `no-overlap:${classicId}:visual-candidate:${candidate.sourceKey || candidate.elementId || 'rdx-visual'}`,
        sourceKey: classicSourceKey,
        rdxSourceKey: candidate.sourceKey || null,
        category: 'no-overlap', subjectCategory: 'hazard', classification: 'candidate-rdx-hazard-visual-unclassified',
        counterpartState: 'nearby-rdx-visual-needs-hazard-family-review', overlayType: 'candidate-rdx-hazard-visual',
        current: Object.freeze(expectedCenter), bounds: expectedBounds,
        policy: Object.freeze({ family: 'no-overlap', label: 'Nearby RDX visual may be the Classic hazard counterpart' }),
        authority: 'classic-lethal-tile-to-rdx-visual-candidate-audit',
        notes: Object.freeze([
          `Classic ${classicId} projects to [${expectedBounds.x},${expectedBounds.y},${expectedBounds.width},${expectedBounds.height}].`,
          `Nearby RDX visual ${candidate.elementId || candidate.sourceKey || 'unknown'} is ${visualCandidate.distance.toFixed(1)}px away but is not yet classified as a hazard; review its asset family/effect before accepting parity.`
        ])
      }));
      return;
    }

    output.push(Object.freeze({
      debugId: `no-overlap:${classicId}`, sourceKey: `terrain-hazard:${classicId}`,
      category: 'no-overlap', subjectCategory: 'hazard', classification: 'missing-rdx-hazard-effect',
      counterpartState: 'classic-lethal-effect-has-no-reviewed-rdx-hazard', overlayType: 'missing-rdx-hazard',
      current: Object.freeze(expectedCenter), bounds: expectedBounds,
      policy: Object.freeze({ family: 'no-overlap', label: 'Classic lethal terrain has no nearby reviewed RDX hazard' }),
      authority: 'classic-lethal-tile-to-reviewed-rdx-hazard-presence-audit',
      notes: Object.freeze([`Classic ${classicId} projects to [${expectedBounds.x},${expectedBounds.y},${expectedBounds.width},${expectedBounds.height}] but no reviewed RDX hazard exists within 40px.`])
    }));
  });
  return Object.freeze(output);
}
